// Package agentdef generates files from the agent charters in
// system/agents: a Claude Code agent definition per agent, so
// `claude --agent <id>` starts a session that already knows its scope, owned
// paths, rules, and how to work its tasks; and the GitHub CODEOWNERS file,
// so changes to each owned path ask its reviewers.
package agentdef

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/JuanVizcaya/fausto/internal/spec"
)

// Dir holds the generated definitions, relative to the repository root.
const Dir = ".claude/agents"

// generatedBy marks generated files; files without it are left alone.
const generatedBy = "Generated by `fausto agents`"

// Path returns the definition file for agent id.
func Path(id string) string { return Dir + "/" + id + ".md" }

// Want returns the generated files, by path: the definition each charter of
// kind agent should have (charters of humans, like the orchestrator, get
// none), and CODEOWNERS when a charter names reviewers.
func Want(s *spec.Spec) map[string][]byte {
	out := map[string][]byte{}
	for i := range s.Agents {
		if a := &s.Agents[i]; a.Kind == "agent" {
			out[Path(a.ID)] = Render(s, a)
		}
	}
	if co := RenderCodeOwners(s); co != nil {
		out[CodeOwners] = co
	}
	return out
}

// Sync compares the generated files under root with the charters and
// returns the files to write, with nil for generated files no longer wanted
// (a definition whose charter is gone, or CODEOWNERS once no charter names
// reviewers). A CODEOWNERS file fausto didn't write is replaced only when
// one is wanted.
// An empty result means they are up to date.
func Sync(root string, s *spec.Spec) (map[string][]byte, error) {
	want := Want(s)
	out := map[string][]byte{}
	for path, data := range want {
		cur, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			return nil, err
		}
		if !bytes.Equal(cur, data) {
			out[path] = data
		}
	}
	existing, _ := filepath.Glob(filepath.Join(root, filepath.FromSlash(Dir), "*.md"))
	existing = append(existing, filepath.Join(root, filepath.FromSlash(CodeOwners)))
	for _, p := range existing {
		path, _ := filepath.Rel(root, p)
		path = filepath.ToSlash(path)
		if _, ok := want[path]; ok {
			continue
		}
		data, err := os.ReadFile(p)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		if bytes.Contains(data, []byte(generatedBy)) {
			out[path] = nil
		}
	}
	return out, nil
}

// Write applies the files Sync returned under root.
func Write(root string, files map[string][]byte) error {
	for path, data := range files {
		p := filepath.Join(root, filepath.FromSlash(path))
		if data == nil {
			if err := os.Remove(p); err != nil && !errors.Is(err, fs.ErrNotExist) {
				return err
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Render returns the definition for agent a.
func Render(s *spec.Spec, a *spec.Agent) []byte {
	var b strings.Builder
	front, _ := yaml.Marshal(struct {
		Name        string `yaml:"name"`
		Description string `yaml:"description"`
	}{
		Name: a.ID,
		Description: fmt.Sprintf("%s for %s. %s Use it to work the fausto tasks assigned to agent `%s`.",
			a.Name, s.System.Name, strings.TrimSpace(a.Scope), a.ID),
	})
	charter := a.File
	if charter == "" {
		charter = spec.Dir + "/agents/" + a.ID + ".yaml"
	}
	fmt.Fprintf(&b, "---\n%s---\n\n", front)
	fmt.Fprintf(&b, "<!-- %s from %s. Don't edit it: change the charter through a fausto proposal. -->\n\n", generatedBy, charter)
	fmt.Fprintf(&b, "You are the **%s** in the %s project. Several agents build %s, each in its own area. "+
		"An orchestrator (a human) decides the architecture in `%s/` and assigns work to agents as fausto tasks.\n\n",
		a.Name, s.System.Name, s.System.Name, spec.Dir)

	fmt.Fprintf(&b, "## Your scope\n\n%s\n\n", strings.TrimSpace(a.Scope))

	b.WriteString("## What you own\n\nYou may change only these paths (directories end in `/`):\n\n")
	for _, p := range a.Owns {
		fmt.Fprintf(&b, "- `%s`\n", p)
	}
	var owned []string
	for _, c := range s.System.Components {
		if c.Owner != a.ID {
			continue
		}
		line := fmt.Sprintf("- `%s` (%s): %s in the %s layer, %s", c.ID, c.Name, c.Kind, c.Layer, c.Status)
		if len(c.Tech) > 0 {
			line += "; " + strings.Join(c.Tech, ", ")
		}
		owned = append(owned, line+".")
	}
	if len(owned) > 0 {
		fmt.Fprintf(&b, "\nComponents you own, declared in `%s/system.yaml` with their dependencies, contracts, and data:\n\n%s\n", spec.Dir, strings.Join(owned, "\n"))
	}

	b.WriteString("\n## Your rules\n\n")
	for _, r := range a.Rules {
		fmt.Fprintf(&b, "- %s\n", strings.TrimSpace(r))
	}
	if len(a.Rules) > 0 {
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "Also follow every principle in `%s/principles.yaml`:\n\n", spec.Dir)
	for _, p := range s.Principles.Principles {
		fmt.Fprintf(&b, "- **%s** (`%s`)\n", strings.TrimSpace(p.Title), p.ID)
	}

	fmt.Fprintf(&b, `
## How to work

1. Read `+"`CLAUDE.md`"+`, your charter `+"`%[1]s`"+`, and the parts of `+"`%[2]s/`"+` your task touches.
2. Get your tasks: from the repository root, run `+"`fausto task pull %[3]s`"+`. It writes your open and in-progress tasks to `+"`.fausto/tasks/`"+` (git-ignored; never commit them). Work them oldest first; their names start with the date. Run `+"`fausto task start <id>`"+` when you start one.
3. Change only the paths you own. If a task needs a change anywhere else, in another agent's paths or in `+"`%[2]s/`"+`, don't make it: describe what you need in your summary so the orchestrator can propose it.
4. Run the drift checks and fix what they report in your area. From the repository root:

   `+"```sh"+`
   fausto check
   `+"```"+`

   Without fausto installed (`+"`go install github.com/JuanVizcaya/fausto/cmd/fausto@latest`"+`):

   `+"```sh"+`
   docker run --rm -v "$PWD":/repo ghcr.io/juanvizcaya/fausto check
   `+"```"+`

5. When the checks pass, commit on your branch with the task id in the message, then run `+"`fausto task done <id>`"+`.
6. Finish with a summary: what you did for each task, anything you couldn't do and why, and the changes you need from other agents or the orchestrator.
`, charter, spec.Dir, a.ID)
	return []byte(b.String())
}
