package check

import (
	"os"
	"path/filepath"
	"sort"

	"github.com/JuanVizcaya/fausto/internal/agentdef"
)

// checkAgents verifies that the files generated from the agent charters,
// the Claude Code agent definitions in .claude/agents and .github/CODEOWNERS,
// match the charters.
func checkAgents(r *Repo) []Finding {
	stale, err := agentdef.Sync(r.Root, r.Spec)
	if err != nil {
		return []Finding{{Message: err.Error(), Path: agentdef.Dir}}
	}
	paths := make([]string, 0, len(stale))
	for p := range stale {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var out []Finding
	for _, p := range paths {
		// One message per state: out of date, orphaned, missing.
		msgs := [3]string{
			"agent definition is out of date with its charter; run `fausto agents` to regenerate",
			"agent definition has no charter any more; run `fausto agents` to regenerate",
			"agent definition is missing; run `fausto agents` to regenerate",
		}
		if p == agentdef.CodeOwners {
			msgs = [3]string{
				"CODEOWNERS is out of date with the agent charters; run `fausto agents` to regenerate",
				"CODEOWNERS was generated by fausto but no charter names reviewers any more; run `fausto agents` to remove it",
				"CODEOWNERS is missing; run `fausto agents` to generate it from the charters' reviewers",
			}
		}
		msg := msgs[0]
		if stale[p] == nil {
			msg = msgs[1]
		} else if _, err := os.Stat(filepath.Join(r.Root, filepath.FromSlash(p))); err != nil {
			msg = msgs[2]
		}
		out = append(out, Finding{Message: msg, Path: p})
	}
	return out
}
