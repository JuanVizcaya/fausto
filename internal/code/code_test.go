func writeFile(root, rel, content string) error {
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, []byte(content), 0o644)
}

func analyze(t *testing.T, root, component string) *Model {
	t.Helper()
	m, err := (&Analyzer{Root: root}).Analyze(component)
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func pkgOf(t *testing.T, m *Model, dir string) Package {
	t.Helper()
	for _, p := range m.Packages {
		if p.Dir == dir {
			return p
		}
	}
	t.Fatalf("no package %s in %v", dir, m.Packages)
	return Package{}
}

func hasRelation(p Package, from, to, kind string) bool {
	return slices.ContainsFunc(p.Relations, func(r Relation) bool { return r.From == from && r.To == to && r.Kind == kind })
}

func hasCall(m *Model, from, to string) bool {
	return slices.ContainsFunc(m.Calls, func(c Call) bool { return c.From == from && c.To == to })
}

const (
	res = "backend/internal/residents"
	gen = "backend/gen/habyta/residents/v1"
)

func TestPackages(t *testing.T) {
	m := analyze(t, fixture(t), "residents")
	if got := pkgOf(t, m, "backend/cmd/residents").Role; got != "cmd" {
		t.Errorf("cmd role = %q", got)
	}
	if got := pkgOf(t, m, gen).Role; got != "generated" {
		t.Errorf("gen role = %q", got)
	}
	p := pkgOf(t, m, res)
	if p.Role != "internal" || p.Doc != "Package residents is the residents service." || !p.Database {
		t.Errorf("residents package = %+v", p)
	}
	kinds := map[string]string{}
	for _, imp := range p.Imports {
		kinds[imp.Dir] = imp.Kind
	}
	if kinds[gen] != "same" || kinds["backend/internal/platform/server"] != "library" {
		t.Errorf("import kinds = %v", kinds)
	}
	if len(m.Neighbors) != 1 || m.Neighbors[0].Name != "server" || m.Neighbors[0].Component != "platform" {
		t.Errorf("neighbors = %+v", m.Neighbors)
	}

	plat := analyze(t, fixture(t), "platform")
	if !slices.ContainsFunc(plat.Dependents, func(d Dependent) bool { return d.From == res && d.Component == "residents" }) {
		t.Errorf("platform dependents = %+v", plat.Dependents)
	}
}

func TestRelations(t *testing.T) {
	m := analyze(t, fixture(t), "residents")
	p := pkgOf(t, m, res)
	// Through an embedded interface, and with a method promoted from an
	// embedded struct of another package.
	if !hasRelation(p, res+"#postgresStore", res+"#store", "implements") {
		t.Errorf("postgresStore should implement store: %+v", p.Relations)
	}
	if !hasRelation(p, res+"#service", gen+"#ResidentServiceServer", "implements") {
		t.Errorf("service should implement ResidentServiceServer: %+v", p.Relations)
	}
	if hasRelation(p, res+"#service", gen+"#UnsafeResidentServiceServer", "implements") {
		t.Error("a marker interface of unexported methods shouldn't count")
	}
	if !hasRelation(p, res+"#service", gen+"#UnimplementedResidentServiceServer", "embeds") ||
		!hasRelation(p, res+"#store", res+"#reader", "embeds") {
		t.Errorf("embedding: %+v", p.Relations)
	}
	if !slices.ContainsFunc(p.Relations, func(r Relation) bool {
		return r.From == res+"#service" && r.To == res+"#store" && r.Kind == "has" && r.Label == "store"
	}) {
		t.Errorf("service should have a store: %+v", p.Relations)
	}
	if !hasRelation(p, res+"#reader", res+"#resident", "uses") {
		t.Errorf("reader should use resident: %+v", p.Relations)
	}
	// The generated contract is the component's own code, not a stub.
	if len(m.Stubs) != 0 {
		t.Errorf("stubs = %+v", m.Stubs)
	}
}

func TestCalls(t *testing.T) {
	m := analyze(t, fixture(t), "residents")
	for _, c := range [][2]string{
		{"backend/cmd/residents#main", res + "#Run"},
		{res + "#Run", "backend/internal/platform/server#New"},
		// Through a local whose type a call returns.
		{res + "#Run", "backend/internal/platform/server#Server.Register"},
		{res + "#Run", res + "#newService"},
		// Through a field of the receiver, to the interface that declares it.
		{res + "#service.GetResident", res + "#reader.get"},
	} {
		if !hasCall(m, c[0], c[1]) {
			t.Errorf("no call %s → %s in %+v", c[0], c[1], m.Calls)
		}
	}
}

func TestRPCs(t *testing.T) {
	root := fixture(t)
	rpc := Call{From: gen + "#ResidentServiceClient.GetResident", To: res + "#service.GetResident", Kind: "rpc"}
	// The server's model shows who calls it over gRPC.
	if m := analyze(t, root, "residents"); !slices.Contains(m.Calls, rpc) {
		t.Errorf("residents calls = %+v", m.Calls)
	}
	// The gateway's model follows its client call to the server.
	api := analyze(t, root, "api")
	if !slices.Contains(api.Calls, rpc) || !hasCall(api, "backend/internal/api#gateway.getResident", rpc.From) {
		t.Errorf("api calls = %+v", api.Calls)
	}
	if d := api.Dirs[res]; d.Name != "residents" || d.Component != "residents" {
		t.Errorf("api dirs = %+v", api.Dirs)
	}
}

func TestGeneratedCodeKeepsItsAPI(t *testing.T) {
	p := pkgOf(t, analyze(t, fixture(t), "residents"), gen)
	for _, f := range p.Funcs {
		if !f.Exported {
			t.Errorf("unexported generated func %s", f.Name)
		}
	}
	for _, ty := range p.Types {
		if ty.Name == "GetResidentRequest" && (len(ty.Fields) != 1 || ty.Fields[0].Name != "Id") {
			t.Errorf("message fields = %+v", ty.Fields)
		}
		if ty.Source != "" {
			t.Errorf("generated %s keeps its source", ty.Name)
		}
	}
}

func TestContract(t *testing.T) {
	m := analyze(t, fixture(t), "residents")
	if len(m.Contracts) != 1 {
		t.Fatalf("contracts = %+v", m.Contracts)
	}
	ct := m.Contracts[0]
	if len(ct.Services) != 1 || ct.Services[0].Name != "ResidentService" || len(ct.Services[0].RPCs) != 2 {
		t.Fatalf("services = %+v", ct.Services)
	}
	w := ct.Services[0].RPCs[1]
	if w.Name != "WatchResidents" || !w.ClientStreams || !w.ServerStreams || w.Response != "GetResidentResponse" {
		t.Errorf("rpc = %+v", w)
	}
	if !slices.Equal(ct.Messages, []string{"GetResidentRequest", "GetResidentResponse"}) {
		t.Errorf("messages = %v", ct.Messages)
	}
}

