// The real residents service implements its generated gRPC server.
func TestRepository(t *testing.T) {
	m := analyze(t, repoRoot, "residents")
	p := pkgOf(t, m, res)
	if !slices.ContainsFunc(p.Relations, func(r Relation) bool {
		return r.Kind == "implements" && r.To == gen+"#ResidentServiceServer"
	}) {
		t.Errorf("no type implements ResidentServiceServer: %+v", p.Relations)
	}
	// Same method names, different shape.
	if slices.ContainsFunc(p.Relations, func(r Relation) bool {
		return r.Kind == "implements" && r.To == gen+"#ResidentServiceClient"
	}) {
		t.Errorf("the server shouldn't implement the client: %+v", p.Relations)
	}
	// The gateway holds a client of the residents contract.
	api := analyze(t, repoRoot, "api")
	if !slices.ContainsFunc(api.Stubs, func(s Stub) bool {
		return s.ID == gen+"#ResidentServiceClient" && s.Kind == "interface" && s.Component == "residents" &&
			slices.Contains(s.Methods, "GetResident")
	}) {
		t.Errorf("api stubs = %+v", api.Stubs)
	}
	if !slices.ContainsFunc(api.Calls, func(c Call) bool {
		return c.From == "backend/internal/api#gateway.getResident" && c.To == gen+"#ResidentServiceClient.GetResident"
	}) {
		t.Errorf("api calls = %+v", api.Calls)
	}
	if !slices.Contains(api.Calls, Call{From: gen + "#ResidentServiceClient.CreateResident", To: res + "#residentService.CreateResident", Kind: "rpc"}) {
		t.Errorf("the gateway's CreateResident call doesn't reach the server: %+v", api.Calls)
	}
	for _, c := range m.Calls {
		if strings.Contains(c.To, ".Get") && strings.HasPrefix(c.To, gen+"#") && !strings.Contains(c.To, "Client.") {
			t.Errorf("message getter call %s → %s", c.From, c.To)
		}
	}
}
